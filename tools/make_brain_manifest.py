"""Builds app/src/main/assets/brain_manifest.tsv from the Hugging Face API.

Every file is pinned to one commit, with its size and (for LFS files) its SHA-256, so every
phone downloads exactly the same brain. Rerun only when a model is deliberately updated:
    python tools/make_brain_manifest.py
"""
import json, os, urllib.request

SOURCES = [
    # repo, commit, (path in repo -> target under files/models)
    ("litert-community/gemma-4-E2B-it-litert-lm", "2e12bfd869b2962984f97a1f2a26807316d534cc",
     {"gemma-4-E2B-it.litertlm": "gemma/gemma-4-E2B-it.litertlm"}),
    ("csukuangfj/sherpa-onnx-whisper-small", "8f3c18b358db4d1f2fc1eae49d75cd20989e4309",
     {"small-encoder.int8.onnx": "asr/small-encoder.int8.onnx",
      "small-decoder.int8.onnx": "asr/small-decoder.int8.onnx",
      "small-tokens.txt": "asr/small-tokens.txt"}),
    ("csukuangfj/vad", "fba88cd2e921609e7675c3aaf51e0b9b295da4bc",
     {"silero_vad_v5.onnx": "vad/silero_vad_v5.onnx"}),
    # Kerstin (CC0) in its own folder, the phonemiser shared in tts/de – the layout ModelStore already knows
    ("csukuangfj/vits-piper-de_DE-kerstin-low", "7bc6590b34162daac7af36a49817c5ac9799eced",
     {"de_DE-kerstin-low.onnx": "tts/de/kerstin/de_DE-kerstin-low.onnx",
      "de_DE-kerstin-low.onnx.json": "tts/de/kerstin/de_DE-kerstin-low.onnx.json",
      "tokens.txt": "tts/de/kerstin/tokens.txt",
      "espeak-ng-data/": "tts/de/espeak-ng-data/"}),
]

rows = []
for repo, rev, mapping in SOURCES:
    with urllib.request.urlopen(f"https://huggingface.co/api/models/{repo}/tree/{rev}?recursive=true") as r:
        tree = [x for x in json.load(r) if x.get("type") == "file"]
    for f in tree:
        p = f["path"]
        target = mapping.get(p)
        if target is None:
            prefix = next((k for k in mapping if k.endswith("/") and p.startswith(k)), None)
            if prefix is None:
                continue
            target = mapping[prefix] + p[len(prefix):]
        sha = (f.get("lfs") or {}).get("oid", "-")
        rows.append((f"https://huggingface.co/{repo}/resolve/{rev}/{p}", target, f["size"], sha))

out = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "assets", "brain_manifest.tsv")
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("# url\ttarget\tsize\tsha256  (generated by tools/make_brain_manifest.py)\n")
    for row in rows:
        fh.write("\t".join(str(x) for x in row) + "\n")
print(len(rows), "files,", round(sum(r[2] for r in rows) / 1e9, 3), "GB ->", os.path.normpath(out))
